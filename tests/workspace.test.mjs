import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {collectionTotals,purchaseSavings,comparisonWinner,offerTotal} from '../lib/workspace.ts';
const A='00000000-0000-0000-0000-000000000001',B='00000000-0000-0000-0000-000000000002';
const P='10000000-0000-0000-0000-000000000001',Q='10000000-0000-0000-0000-000000000002',R='10000000-0000-0000-0000-000000000003';
test('budgets and actual purchase savings respect currency and unknown delivery',()=>{
 const collection={id:'desk',budget:500,currency:'INR'};
 const purchase={collection_id:'desk',currency:'INR',paid_price:80,quantity:2,baseline_price:100};
 assert.equal(purchaseSavings(purchase),40);
 assert.equal(purchaseSavings({...purchase,paid_price:120}),-40);
 assert.equal(purchaseSavings({...purchase,baseline_price:null}),null);
 assert.deepEqual(collectionTotals(collection,[{collection_id:'desk',currency:'INR',current_price:200},{collection_id:'desk',currency:'USD',current_price:999},{collection_id:'desk',currency:'INR',current_price:NaN}],[purchase]),{spent:160,wishlist:200,projected:360,unknown:1,count:2,remaining:140});
 const offers=[{product_id:'a',current_price:100,shipping_cost:0,currency:'INR',stock_status:'in_stock'},{product_id:'b',current_price:90,shipping_cost:20,currency:'INR',stock_status:'in_stock'}];
 assert.equal(offerTotal(offers[1]),110);assert.equal(comparisonWinner(offers),'a');
 assert.equal(comparisonWinner([offers[0],{...offers[1],shipping_cost:null}]),null);
 assert.equal(comparisonWinner([offers[0],{...offers[1],currency:'USD'}]),null);
});
test('workspace ownership, public projection/revocation, purchases, comparisons and restock transitions',async()=>{
 const db=new PGlite();
 try {
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create table auth.users(id uuid primary key);
  create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
  grant usage on schema public,auth to anon,authenticated,service_role;grant execute on function auth.uid() to authenticated;
  insert into auth.users values('${A}'),('${B}');
  create table public.products(id uuid primary key default gen_random_uuid(),user_id uuid references auth.users(id),url text not null,name text,current_price numeric,currency text,image_url text,updated_at timestamp,created_at timestamptz default now(),unique(user_id,url));
  create table public.price_history(id uuid primary key default gen_random_uuid(),product_id uuid not null references public.products(id),price numeric not null,currency text,checked_at timestamp not null default now());
  insert into public.products(id,user_id,url,name,current_price,currency,updated_at) values('${P}','${A}','https://amazon.in/dp/B09Y2MYL5C','Same model',100,'INR',now()-interval '2 hours'),('${Q}','${A}','https://flipkart.com/model/p/itm1?pid=MODEL1','Same model',90,'INR',now()-interval '2 hours'),('${R}','${B}','https://amazon.in/dp/B09Y2MYL5C','Same model',100,'INR',now()-interval '2 hours');`);
  for(const file of ['001_shared_tracking.sql','002_shopping_workspace.sql'])await db.exec(await readFile(new URL('../migrations/'+file,import.meta.url),'utf8'));
  const row=async(q,params=[])=>(await db.query(q,params)).rows[0];
  await db.exec(`set role authenticated;set request.jwt.claim.sub='${A}'`);
  const {id:c}=await row(`insert into collections(user_id,name,budget,currency) values('${A}','Desk',500,'INR') returning id`);
  await db.query('select assign_collection($1,$2)',[P,c]);
  await assert.rejects(db.query('select assign_collection($1,$2)',[R,c]),'cannot move a foreign product');
  await assert.rejects(db.exec(`insert into collections(user_id,name,is_public) values('${A}','Bypass',true)`),'sharing requires explicit RPC');
  const {token}=await row('select set_collection_sharing($1,true) token',[c]);
  await db.exec('reset role;set role anon');
  const {value}=await row('select public_wishlist($1) value',[token]);
  assert.equal(value.name,'Desk');assert.equal(value.items.length,1);
  for(const key of ['user_id','budget','share_token','target_price','purchase'])assert.ok(!(key in value));
  assert.ok(!('product_id' in value.items[0]));
  await assert.rejects(db.query('select * from collections'),'public RPC does not grant table access');
  await db.exec(`reset role;set role authenticated;set request.jwt.claim.sub='${B}'`);
  assert.equal((await row('select count(*)::int n from collections')).n,0);
  await assert.rejects(db.query('select set_collection_sharing($1,true)',[c]));
  await db.exec(`reset role;set role authenticated;set request.jwt.claim.sub='${A}'`);
  const {id:purchase}=await row('select record_purchase($1,80,2,current_date) id',[P]);
  assert.equal(Number((await row('select paid_price from purchases where id=$1',[purchase])).paid_price),80);
  assert.equal((await row('select paused from products where id=$1',[P])).paused,true);
  assert.equal((await row('select public_wishlist($1) value',[token])).value.items.length,0,'bought items are excluded from gift lists');
  await assert.rejects(db.query('select record_purchase($1,1,1,current_date)',[R]));
  await db.query('select remove_purchase($1)',[purchase]);
  assert.equal((await row('select paused from products where id=$1',[P])).paused,false);
  await assert.rejects(db.query('select link_comparison($1,$2,false,0)',[P,Q]));
  await assert.rejects(db.query('select link_comparison($1,$2,true,0)',[P,R]));
  const {g}=await row('select link_comparison($1,$2,true,20) g',[P,Q]);
  assert.equal((await row('select count(*)::int n from products where comparison_group_id=$1',[g])).n,2);
  await db.query('select set_collection_sharing($1,false)',[c]);
  await db.exec('reset role;set role anon');assert.equal((await row('select public_wishlist($1) value',[token])).value,null,'old link revoked immediately');
  await db.exec(`reset role;set role authenticated;set request.jwt.claim.sub='${A}';update products set restock_enabled=true where id='${P}';reset role`);
  const {catalog_id:id}=await row(`select catalog_id from products where id='${P}'`);
  async function observe(price,stock){
    await db.query("update catalog_products set checked_at=now()-interval '2 hours',next_check_at=null where id=$1",[id]);
    await db.exec('set role service_role');const {t}=await row('select claim_catalog_check($1) t',[id]);assert.ok(t);
    await db.query('select complete_catalog_check($1,$2,$3,$4,$5,$6,$7,$8)',[id,t,'Same model',price,'INR',null,stock,null]);await db.exec('reset role');
  }
  const before=(await row('select count(*)::int n from catalog_price_history')).n;
  await observe(null,'out_of_stock');
  assert.equal((await row('select count(*)::int n from catalog_price_history')).n,before,'missing stock price does not fabricate a history observation');
  assert.equal(Number((await row('select current_price from products where id=$1',[P])).current_price),100,'last quote retained');
  await observe(95,'in_stock');assert.equal((await row("select count(*)::int n from alert_events where kind='restock'")).n,1);
  await observe(95,'in_stock');assert.equal((await row("select count(*)::int n from alert_events where kind='restock'")).n,1,'repeated in-stock checks do not spam');
  const {id:alert}=await row("select id from alert_events where kind='restock'");
  await db.exec('set role service_role');assert.ok((await row('select claim_alert($1) token',[alert])).token,'restock delivery works without price alerts');await db.exec('reset role');
  await db.exec(`set role authenticated;set request.jwt.claim.sub='${A}'`);
  await db.query('select record_purchase($1,80,1,current_date)',[P]);await db.query('delete from products where id=$1',[P]);
  assert.equal((await row('select count(*)::int n from purchases')).n,1,'purchase survives deleting tracker');
  assert.equal((await row('select product_id from purchases')).product_id,null);
 }finally{await db.close();}
});
